// Actual migrations in isolated PostgreSQL; synthetic accounts, no live service.
// Usage: node tests/participation-db.mjs /absolute/path/to/pglite/dist/index.js
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const {PGlite}=await import(process.argv[2]);
const db=new PGlite();
const checks=[];
const check=(condition,name)=>{assert.ok(condition,name);checks.push(name);};
const user='00000000-0000-4000-8000-000000000001';
const other='00000000-0000-4000-8000-000000000002';
const observation='00000000-0000-4000-8000-000000000003';
const nextObservation='00000000-0000-4000-8000-000000000004';
const thirdObservation='00000000-0000-4000-8000-000000000005';
const identity=async(id=user,anonymous=false)=>{
 await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:id,is_anonymous:anonymous})]);
};
const summary=async()=>(await db.query('select public.participation_summary() as r')).rows[0].r;
const claim=async(id=observation,date=today)=>(await db.query('select public.claim_daily_observation($1::uuid,$2::date) as r',[id,date])).rows[0].r;
let today;
try{
 await db.exec(`create role anon; create role authenticated; create role service_role;
 create schema auth; create table auth.users(id uuid primary key);
 create function auth.jwt() returns jsonb language sql as $$select nullif(current_setting('request.jwt.claims',true),'')::jsonb$$;
 create function auth.uid() returns uuid language sql as $$select (auth.jwt()->>'sub')::uuid$$;
 grant usage on schema auth to authenticated;
 `);
 await db.query('insert into auth.users(id) values($1),($2)',[user,other]);
 await db.exec(await readFile('supabase/migrations/20261029000000_discovery_game.sql','utf8'));
 await db.exec(await readFile('supabase/migrations/20261029010000_participation.sql','utf8'));
 today=(await db.query("select ((now() at time zone 'Asia/Seoul')::date)::text as d")).rows[0].d;
 const yesterday=(await db.query("select ((now() at time zone 'Asia/Seoul')::date-1)::text as d")).rows[0].d;
 const tomorrow=(await db.query("select ((now() at time zone 'Asia/Seoul')::date+1)::text as d")).rows[0].d;
 await identity();
 await db.exec('set role anon');
 await assert.rejects(summary,/permission denied/);await assert.rejects(()=>claim(),/permission denied/);
 checks.push('anonymous role cannot read summary or claim');
 await db.exec('reset role; set role authenticated');
 await identity(null);await assert.rejects(summary,/login_required/);await assert.rejects(()=>claim(),/login_required/);
 checks.push('missing authenticated identity rejected');
 await identity(user,true);await assert.rejects(summary,/login_required/);await assert.rejects(()=>claim(),/login_required/);
 checks.push('anonymous Supabase user rejected despite authenticated role');
 await identity();
 const empty=await summary();
 check(empty.totalPoints===0&&empty.tier==='seed'&&!empty.todayClaimed&&empty.serverDate===today,'new member has zero score and server KST day');
 for(const date of [null,yesterday,tomorrow])await assert.rejects(()=>claim(observation,date),/today_observation_required/);
 await assert.rejects(()=>claim(null),/today_observation_required/);
 checks.push('null record and past/future/null observation date rejected');
 const first=await claim();
 check(first.awarded===2&&first.totalPoints===2&&first.todayClaimed&&first.observationDays===1,'first daily claim earns two points');
 const duplicate=await claim();
 check(duplicate.awarded===0&&duplicate.totalPoints===2&&duplicate.claimStatus==='already_today','duplicate retry idempotent');
 const another=await claim(nextObservation);
 check(another.awarded===0&&another.observationDays===1,'different record cannot claim same day twice');
 const attempts=await Promise.all([claim(nextObservation),claim(thirdObservation)]);
 check(attempts.every(r=>r.awarded===0&&r.totalPoints===2),'overlapping duplicate requests do not increase points');
 await assert.rejects(()=>db.query('select * from public.daily_observation_participation'),/permission denied/);
 await assert.rejects(()=>db.query('update public.daily_observation_participation set points=100'),/permission denied/);
 await assert.rejects(()=>db.query('delete from public.daily_observation_participation'),/permission denied/);
 await assert.rejects(()=>db.query('insert into public.daily_observation_participation values($1,$2,$3,2,now())',[user,today,nextObservation]),/permission denied/);
 checks.push('authenticated client cannot read, insert, edit or delete ledger');
 await identity(other);
 check((await summary()).totalPoints===0,'other account cannot read first account score');
 check((await claim()).awarded===2,'other account has its own daily allowance');
 await db.exec('reset role');
 await assert.rejects(()=>db.query('insert into public.daily_observation_participation(user_id,participation_day,observation_id) values($1,$2::date,$3)',[user,today,nextObservation]),/duplicate key/);
 await assert.rejects(()=>db.query('insert into public.daily_observation_participation(user_id,participation_day,observation_id) values($1,$2::date,$3)',[user,yesterday,observation]),/duplicate key/);
 checks.push('database uniqueness independently enforces day and lifetime record limits');
 await db.query('update public.daily_observation_participation set participation_day=$1::date where user_id=$2',[yesterday,user]);
 await db.exec('set role authenticated');await identity();
 const replay=await claim();
 check(replay.awarded===0&&!replay.todayClaimed&&replay.claimStatus==='already_recorded','old observation UUID cannot earn again on new day');
 const next=await claim(nextObservation);
 check(next.awarded===2&&next.observationDays===2&&next.totalPoints===4,'new day and new record accumulate');
 // Verify date is independent of database/session timezone.
 await db.exec("set timezone='Pacific/Honolulu'");
 check((await summary()).serverDate===today,'session timezone cannot alter participation day');
 await db.exec('reset role');
 // Fixture prior legitimate game awards; never call a live user's scoring RPC.
 for(let i=0;i<2;i++)await db.query("insert into public.discovery_rounds(user_id,photo_hash,observation_id,state,points) values($1,$2,'fixture','revealed',10)",[user,String(i).repeat(64)]);
 await db.exec('set role authenticated');
 const sprout=await summary();
 check(sprout.predictionPoints===20&&sprout.dailyPoints===4&&sprout.totalPoints===24&&sprout.tier==='sprout','summary combines prediction and daily points for sprout tier');
 await db.exec('reset role');
 for(let i=2;i<10;i++)await db.query("insert into public.discovery_rounds(user_id,photo_hash,observation_id,state,points) values($1,$2,'fixture','revealed',10)",[user,String(i).repeat(64)]);
 await db.exec('set role authenticated');
 check((await summary()).tier==='tree','100 combined points reaches tree tier');
 await identity(other);check((await summary()).totalPoints===2,'other account aggregate excludes all first-account prediction points');
 await db.exec('reset role');
 const before=await db.query('select count(*)::int as n from public.daily_observation_participation');
 await db.query('delete from auth.users where id=$1',[other]);
 const after=await db.query('select count(*)::int as n from public.daily_observation_participation');
 check(before.rows[0].n-after.rows[0].n===1,'account deletion cascades new participation ledger');
 // Exact tier boundaries on a fresh fixture member, without changing point values.
 await db.query('insert into auth.users(id) values($1)',[thirdObservation]);
 for(let i=1;i<=9;i++)await db.query("insert into public.daily_observation_participation(user_id,participation_day,observation_id) values($1,$2::date-$3::int,gen_random_uuid())",[thirdObservation,today,i]);
 await db.exec('set role authenticated');await identity(thirdObservation);
 check((await summary()).totalPoints===18&&(await summary()).tier==='seed','18 points remains seed');
 check((await claim()).totalPoints===20&&(await summary()).tier==='sprout','20 points becomes sprout');
 await db.exec('reset role');
 for(let i=10;i<=48;i++)await db.query("insert into public.daily_observation_participation(user_id,participation_day,observation_id) values($1,$2::date-$3::int,gen_random_uuid())",[thirdObservation,today,i]);
 await db.exec('set role authenticated');
 check((await summary()).totalPoints===98&&(await summary()).tier==='sprout','98 points remains sprout');
 await db.exec('reset role');
 await db.query("insert into public.daily_observation_participation(user_id,participation_day,observation_id) values($1,$2::date-49,gen_random_uuid())",[thirdObservation,today]);
 await db.exec('set role authenticated');
 check((await summary()).totalPoints===100&&(await summary()).tier==='tree','100 points becomes tree exactly');
 await db.exec('set role authenticated');await identity();
 await assert.rejects(()=>db.query('select public.claim_daily_observation($1,$2,$3)',[user,thirdObservation,today]),/does not exist/);
 checks.push('RPC offers no caller-supplied user ID');
 console.log(JSON.stringify({passed:checks.length,checks,scope:'isolated PGlite SQL with simulated auth JWT; not live service',limitation:'Self-reported date and record ID do not establish photo quality or prevent multi-account farming.'},null,2));
}finally{await db.close();}

import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('same specimen confirmation, persisted timeline, private month and unrelated capture',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/mobile/');
 await page.getByRole('button',{name:'촬영',exact:true}).click();
 await page.getByLabel('앨범 사진 선택').setInputFiles('public/icon-192.png');
 await page.getByLabel('이름 선택').fill('첫 나무');
 await page.getByLabel('한 줄 메모').fill('처음 만난 날');
 await page.getByRole('button',{name:'내 기록에 저장',exact:true}).click();
 await page.getByRole('button',{name:'방금 기록 보기'}).click();
 await page.getByRole('button',{name:'같은 대상 다시 관찰하기'}).click();
 await page.getByLabel('앨범 사진 선택').setInputFiles('public/icon-192.png');
 await expect(page.getByLabel('이름 선택')).toHaveValue('');
 await page.getByRole('button',{name:'내 기록에 저장',exact:true}).click();
 await expect(page.locator('.m-error[role=alert]')).toContainText('같은 개체');
 await page.getByLabel('지난번과 같은 개체를 관찰했습니다').check();
 await page.getByLabel('앨범 사진 선택').setInputFiles('public/icon-192.png');
 await expect(page.getByLabel('지난번과 같은 개체를 관찰했습니다')).not.toBeChecked();
 await page.getByLabel('지난번과 같은 개체를 관찰했습니다').check();
 await page.getByLabel('한 줄 메모').fill('잎 색이 바뀌었어요');
 await page.getByRole('button',{name:'내 기록에 저장',exact:true}).click();
 await page.getByRole('button',{name:'방금 기록 보기'}).click();
 await expect(page.locator('.m-specimen')).toContainText('첫 나무');
 await expect(page.locator('.m-specimen')).toContainText('오늘 만난 자연');
 const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();expect(audit.violations).toEqual([]);
 await page.reload();await page.getByRole('button',{name:'내 기록',exact:true}).click();
 await page.getByRole('button',{name:'오늘 만난 자연 기록 열기'}).click();
 await expect(page.locator('.m-specimen')).toContainText('첫 나무');
 await page.getByRole('button',{name:'저널',exact:true}).click();
 await expect(page.locator('.m-personal-month')).toContainText('2개의 기록 · 1개의 관찰 대상 · 1번의 재관찰');
 await page.getByRole('button',{name:'내 기록으로 도감 펼치기'}).click();
 await expect(page.locator('.m-personal-month')).toContainText('잎 색이 바뀌었어요');
 await page.getByRole('button',{name:'촬영',exact:true}).click();
 await page.getByLabel('앨범 사진 선택').setInputFiles('public/icon-192.png');
 await expect(page.getByLabel('지난번과 같은 개체를 관찰했습니다')).toHaveCount(0);
});
